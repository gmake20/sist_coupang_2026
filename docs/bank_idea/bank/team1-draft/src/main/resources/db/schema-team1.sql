-- 고객(MEMBER)과 직원(EMPLOYEE)은 테이블과 로그인을 완전히 분리한다.
-- 직원 권한 3단계: STAFF(일반 직원) / MANAGER(책임자) / SYSTEM_ADMIN(시스템 관리자)
--
-- 실행 순서: 이 파일 → 다른 팀원 DDL(ACCOUNT 등) → 파일 맨 아래 "ACCOUNT 생성 후 실행" 블록
