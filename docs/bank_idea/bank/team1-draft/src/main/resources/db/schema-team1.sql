-- ---------------------------------------------------------------------
-- 1. MEMBER : 고객 회원 (직원은 EMPLOYEE 테이블)
-- ---------------------------------------------------------------------
CREATE SEQUENCE SEQ_MEMBER START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE MEMBER (
    MEMBER_ID           NUMBER(19)          NOT NULL,
    LOGIN_ID            VARCHAR2(30 CHAR)   NOT NULL,
    PASSWORD            VARCHAR2(100)       NOT NULL,
    NAME                VARCHAR2(30 CHAR)   NOT NULL,
    EMAIL               VARCHAR2(100 CHAR)  NOT NULL,
    PHONE               VARCHAR2(20)        NOT NULL,
    BIRTH_DATE          DATE                NOT NULL,
    STATUS              VARCHAR2(20)        DEFAULT 'ACTIVE' NOT NULL,
    VERIFICATION_STATUS VARCHAR2(20)        DEFAULT 'NONE'   NOT NULL,
    LOGIN_FAIL_COUNT    NUMBER(2)           DEFAULT 0        NOT NULL,
    LOGIN_LOCKED_AT     TIMESTAMP,
    TERMS_AGREED_AT     TIMESTAMP           NOT NULL,
    MARKETING_AGREE_YN  CHAR(1)             DEFAULT 'N'      NOT NULL,
    CREATED_AT          TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP,
    WITHDRAWN_AT        TIMESTAMP,
    CONSTRAINT PK_MEMBER PRIMARY KEY (MEMBER_ID),
    CONSTRAINT UK_MEMBER_LOGIN_ID UNIQUE (LOGIN_ID),
    CONSTRAINT UK_MEMBER_EMAIL UNIQUE (EMAIL),
    CONSTRAINT UK_MEMBER_PHONE UNIQUE (PHONE),
    CONSTRAINT CK_MEMBER_STATUS CHECK (STATUS IN ('ACTIVE', 'SUSPENDED', 'WITHDRAWN')),
    CONSTRAINT CK_MEMBER_VERIFICATION CHECK (VERIFICATION_STATUS IN ('NONE', 'PENDING', 'VERIFIED', 'REJECTED')),
    CONSTRAINT CK_MEMBER_MARKETING CHECK (MARKETING_AGREE_YN IN ('Y', 'N'))
);

COMMENT ON TABLE  MEMBER IS '고객 회원 (직원은 EMPLOYEE)';
COMMENT ON COLUMN MEMBER.LOGIN_ID IS '로그인 아이디 - 탈퇴 후에도 재사용 불가';
COMMENT ON COLUMN MEMBER.PASSWORD IS 'BCrypt 해시';
COMMENT ON COLUMN MEMBER.PHONE IS '숫자만 저장. 탈퇴 시 마스킹';
COMMENT ON COLUMN MEMBER.VERIFICATION_STATUS IS '본인확인 상태: NONE 미확인 / PENDING 심사중 / VERIFIED 완료 / REJECTED 반려';
COMMENT ON COLUMN MEMBER.LOGIN_LOCKED_AT IS '로그인 5회 실패 잠금 시각. NULL이면 잠기지 않음';


-- ---------------------------------------------------------------------
-- 2. BRANCH : 지점/ATM (직원의 소속 지점으로도 사용 → EMPLOYEE보다 먼저 생성)
-- ---------------------------------------------------------------------
CREATE SEQUENCE SEQ_BRANCH START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE BRANCH (
    BRANCH_ID           NUMBER(19)          NOT NULL,
    BRANCH_TYPE         VARCHAR2(10)        NOT NULL,
    NAME                VARCHAR2(50 CHAR)   NOT NULL,
    ADDRESS             VARCHAR2(200 CHAR)  NOT NULL,
    LATITUDE            NUMBER(10, 7)       NOT NULL,
    LONGITUDE           NUMBER(10, 7)       NOT NULL,
    PHONE               VARCHAR2(20),
    BUSINESS_HOURS      VARCHAR2(50 CHAR),
    OPEN_24H_YN         CHAR(1)             DEFAULT 'N' NOT NULL,
    USE_YN              CHAR(1)             DEFAULT 'Y' NOT NULL,
    CREATED_AT          TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP,
    CONSTRAINT PK_BRANCH PRIMARY KEY (BRANCH_ID),
    CONSTRAINT CK_BRANCH_TYPE CHECK (BRANCH_TYPE IN ('BRANCH', 'ATM')),
    CONSTRAINT CK_BRANCH_OPEN_24H CHECK (OPEN_24H_YN IN ('Y', 'N')),
    CONSTRAINT CK_BRANCH_USE CHECK (USE_YN IN ('Y', 'N')),
    CONSTRAINT CK_BRANCH_LAT CHECK (LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT CK_BRANCH_LNG CHECK (LONGITUDE BETWEEN -180 AND 180)
);

CREATE INDEX IX_BRANCH_TYPE ON BRANCH (BRANCH_TYPE, USE_YN);

COMMENT ON TABLE  BRANCH IS '지점/ATM (본점 포함)';
COMMENT ON COLUMN BRANCH.USE_YN IS '삭제 대신 미사용(N) 처리';


-- ---------------------------------------------------------------------
-- 2-1. BRANCH_SERVICE : 지점/ATM 이용 가능 업무 (지점 1곳에 업무 여러 개)
--    JPA: Branch.services (@ElementCollection + BranchServiceType enum)
--    계좌개설/대출상담/카드발급은 창구 업무라 ATM에 등록 불가 → Entity에서 검사
-- ---------------------------------------------------------------------
CREATE TABLE BRANCH_SERVICE (
    BRANCH_ID           NUMBER(19)          NOT NULL,
    SERVICE_CODE        VARCHAR2(30)        NOT NULL,
    CONSTRAINT PK_BRANCH_SERVICE PRIMARY KEY (BRANCH_ID, SERVICE_CODE),
    CONSTRAINT FK_BRANCH_SERVICE_BRANCH FOREIGN KEY (BRANCH_ID) REFERENCES BRANCH (BRANCH_ID),
    CONSTRAINT CK_BRANCH_SERVICE_CODE CHECK (SERVICE_CODE IN (
