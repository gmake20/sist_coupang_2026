COMMENT ON TABLE  BRANCH_SERVICE IS '지점/ATM 이용 가능 업무';
COMMENT ON COLUMN BRANCH_SERVICE.SERVICE_CODE IS 'DEPOSIT 입금 / WITHDRAW 출금 / TRANSFER 이체 / BALANCE_INQUIRY 잔액조회 / ACCOUNT_OPENING 계좌개설 / LOAN_CONSULTING 대출상담 / CARD_ISSUANCE 카드발급';


-- ---------------------------------------------------------------------
-- 3. EMPLOYEE : 은행 직원 (관리자 화면 /admin/** 사용자)
--    ROLE   : STAFF 일반 직원 / MANAGER 책임자 / SYSTEM_ADMIN 시스템 관리자
--    POSITION(직급)은 화면 표시용이며 권한과 무관하다
-- ---------------------------------------------------------------------
CREATE SEQUENCE SEQ_EMPLOYEE START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE EMPLOYEE (
    EMPLOYEE_ID         NUMBER(19)          NOT NULL,
    EMPLOYEE_NO         VARCHAR2(10)        NOT NULL,
    PASSWORD            VARCHAR2(100)       NOT NULL,
    NAME                VARCHAR2(30 CHAR)   NOT NULL,
    EMAIL               VARCHAR2(100 CHAR)  NOT NULL,
    PHONE               VARCHAR2(20),
    BRANCH_ID           NUMBER(19)          NOT NULL,
    POSITION            VARCHAR2(20 CHAR)   NOT NULL,
    ROLE                VARCHAR2(20)        DEFAULT 'STAFF'  NOT NULL,
    STATUS              VARCHAR2(20)        DEFAULT 'ACTIVE' NOT NULL,
    TEMP_PW_YN          CHAR(1)             DEFAULT 'Y'      NOT NULL,
    LOGIN_FAIL_COUNT    NUMBER(2)           DEFAULT 0        NOT NULL,
    LOGIN_LOCKED_AT     TIMESTAMP,
    HIRED_AT            DATE                NOT NULL,
    RETIRED_AT          DATE,
    CREATED_AT          TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP,
    CONSTRAINT PK_EMPLOYEE PRIMARY KEY (EMPLOYEE_ID),
    CONSTRAINT UK_EMPLOYEE_NO UNIQUE (EMPLOYEE_NO),
    CONSTRAINT UK_EMPLOYEE_EMAIL UNIQUE (EMAIL),
    CONSTRAINT FK_EMPLOYEE_BRANCH FOREIGN KEY (BRANCH_ID) REFERENCES BRANCH (BRANCH_ID),
    CONSTRAINT CK_EMPLOYEE_ROLE CHECK (ROLE IN ('STAFF', 'MANAGER', 'SYSTEM_ADMIN')),
    CONSTRAINT CK_EMPLOYEE_STATUS CHECK (STATUS IN ('ACTIVE', 'ON_LEAVE', 'RETIRED')),
    CONSTRAINT CK_EMPLOYEE_TEMP_PW CHECK (TEMP_PW_YN IN ('Y', 'N')),
    -- 퇴사 상태와 퇴사일은 함께 존재
    CONSTRAINT CK_EMPLOYEE_RETIRED CHECK (
        (STATUS = 'RETIRED' AND RETIRED_AT IS NOT NULL) OR (STATUS <> 'RETIRED' AND RETIRED_AT IS NULL)
    )
);

CREATE INDEX IX_EMPLOYEE_BRANCH ON EMPLOYEE (BRANCH_ID);

COMMENT ON TABLE  EMPLOYEE IS '은행 직원 (고객 MEMBER와 분리)';
COMMENT ON COLUMN EMPLOYEE.EMPLOYEE_NO IS '사번 - 직원 로그인 아이디';
COMMENT ON COLUMN EMPLOYEE.BRANCH_ID IS '소속 지점 (BRANCH_TYPE = BRANCH 인 행만, 본점 포함)';
COMMENT ON COLUMN EMPLOYEE.POSITION IS '직급 (사원/대리/과장/차장/부장/지점장 등) - 표시용, 권한과 무관';
COMMENT ON COLUMN EMPLOYEE.ROLE IS '권한: STAFF 일반 직원 / MANAGER 책임자 / SYSTEM_ADMIN 시스템 관리자';
COMMENT ON COLUMN EMPLOYEE.TEMP_PW_YN IS '임시 비밀번호 여부 - Y면 첫 로그인 시 비밀번호 변경 강제';


-- ---------------------------------------------------------------------
-- 4. IDENTITY_VERIFICATION : 본인확인(비대면 실명확인 mock) 심사 이력
--    반려 후 재신청 시 새 행을 추가한다 (기존 행 수정 X)
--    심사 권한: STAFF 이상
-- ---------------------------------------------------------------------
CREATE SEQUENCE SEQ_IDENTITY_VERIFICATION START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE IDENTITY_VERIFICATION (
    VERIFICATION_ID      NUMBER(19)          NOT NULL,
    MEMBER_ID            NUMBER(19)          NOT NULL,
    ID_CARD_TYPE         VARCHAR2(20)        NOT NULL,
    ID_ISSUE_DATE        DATE                NOT NULL,
    AUTH_BANK_NAME       VARCHAR2(30 CHAR)   NOT NULL,
    AUTH_ACCOUNT_MASKED  VARCHAR2(30)        NOT NULL,
    STATUS               VARCHAR2(20)        DEFAULT 'PENDING' NOT NULL,
    REJECT_REASON        VARCHAR2(500 CHAR),
    REQUESTED_AT         TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    REVIEWED_EMPLOYEE_ID NUMBER(19),
    REVIEWED_AT          TIMESTAMP,
    CONSTRAINT PK_IDENTITY_VERIFICATION PRIMARY KEY (VERIFICATION_ID),
    CONSTRAINT FK_IV_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES MEMBER (MEMBER_ID),
    CONSTRAINT FK_IV_EMPLOYEE FOREIGN KEY (REVIEWED_EMPLOYEE_ID) REFERENCES EMPLOYEE (EMPLOYEE_ID),
    CONSTRAINT CK_IV_ID_CARD_TYPE CHECK (ID_CARD_TYPE IN ('RESIDENT_CARD', 'DRIVER_LICENSE')),
    CONSTRAINT CK_IV_STATUS CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED')),
    -- 반려 시 사유 필수
    CONSTRAINT CK_IV_REJECT_REASON CHECK (STATUS <> 'REJECTED' OR REJECT_REASON IS NOT NULL),
    -- 심사 완료 건은 심사 직원/일시 필수
    CONSTRAINT CK_IV_REVIEWED CHECK (STATUS = 'PENDING' OR (REVIEWED_EMPLOYEE_ID IS NOT NULL AND REVIEWED_AT IS NOT NULL))
);

-- 회원당 심사 대기(PENDING)는 1건만 허용 (Oracle은 NULL을 유니크 인덱스에서 제외)
CREATE UNIQUE INDEX UX_IV_ONE_PENDING
    ON IDENTITY_VERIFICATION (CASE WHEN STATUS = 'PENDING' THEN MEMBER_ID END);

CREATE INDEX IX_IV_MEMBER ON IDENTITY_VERIFICATION (MEMBER_ID, REQUESTED_AT);
CREATE INDEX IX_IV_STATUS ON IDENTITY_VERIFICATION (STATUS, REQUESTED_AT);

COMMENT ON TABLE  IDENTITY_VERIFICATION IS '본인확인 심사 이력 - 첫 입출금 계좌 개설 시 생성';
COMMENT ON COLUMN IDENTITY_VERIFICATION.AUTH_ACCOUNT_MASKED IS '1원 인증 타행 계좌번호 (마스킹 값만 저장)';


